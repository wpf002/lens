import { describe, it, expect } from "vitest";
import { branchNameFor, cleanText, commitMessage, pullRequestText, subjectFor } from "../src/commit-text.js";

const NOV_6 = new Date("2026-11-06T12:00:00Z");

describe("cleanText", () => {
  it("drops attribution trailers and AI or Lens as the actor", () => {
    const text = "Escape the query\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n🤖 Generated with Claude Code";
    expect(cleanText(text)).toBe("Escape the query");
    expect(cleanText("Close the handle, found by Lens.")).toBe("Close the handle.");
    expect(cleanText("Rename the helper generated by an AI")).toBe("Rename the helper");
    expect(cleanText("Lens flagged a missing await in save()")).toBe("a missing await in save()");
  });

  it("leaves ordinary uses of the same words alone", () => {
    expect(cleanText("Fix the lens distortion math")).toBe("Fix the lens distortion math");
    expect(cleanText("Cache tokens generated by the client")).toBe("Cache tokens generated by the client");
  });
});

describe("commit text", () => {
  const one = [{ title: "Escape user input in the search query.", files: ["src/search.ts"] }];
  const two = [...one, { title: "close the file handle", files: ["src/io.ts"] }];

  it("uses the fix title as the subject, without a trailing period", () => {
    expect(subjectFor(one, ["src/search.ts"])).toBe("Escape user input in the search query");
    expect(commitMessage(one, ["src/search.ts"])).toBe("Escape user input in the search query");
  });

  it("lists every fix when there's more than one", () => {
    expect(commitMessage(two, [])).toBe("Escape user input in the search query and 1 more fix\n\n- Escape user input in the search query\n- Close the file handle");
  });

  it("falls back to the changed file names", () => {
    expect(subjectFor([], ["src/a.ts"])).toBe("Update a.ts");
    expect(subjectFor([], ["src/a.ts", "b.ts", "c.ts"])).toBe("Update a.ts and 2 other files");
  });

  it("keeps the subject within 72 characters", () => {
    const long = [{ title: "Replace the hand-rolled retry loop around every outbound payment provider request with the shared helper", files: [] }];
    expect(subjectFor(long, []).length).toBeLessThanOrEqual(72);
  });

  it("writes a pull request title and body with no tool names", () => {
    const { title, body } = pullRequestText(two, ["src/search.ts", "src/io.ts"]);
    expect(title).toBe("Escape user input in the search query and 1 more fix");
    expect(body).toBe("- Escape user input in the search query\n- Close the file handle\n\nFiles:\n- `src/io.ts`\n- `src/search.ts`");
  });

  it("names branches fix/<topic>-<date>", () => {
    expect(branchNameFor(one, [], NOV_6)).toBe("fix/escape-user-input-search-20261106");
    expect(branchNameFor([], ["src/upload-handler.ts"], NOV_6)).toBe("fix/upload-handler-20261106");
    expect(branchNameFor([], [], NOV_6)).toBe("fix/updates-20261106");
  });
});
